def fix_dbl(data):
    changes = 0
    reps = {
        b'\xc3\x83\xc2\xa1': b'\xc3\xa1',
        b'\xc3\x83\xc2\xa9': b'\xc3\xa9',
        b'\xc3\x83\xc2\xad': b'\xc3\xad',
        b'\xc3\x83\xc2\xb3': b'\xc3\xb3',
        b'\xc3\x83\xc2\xba': b'\xc3\xba',
        b'\xc3\x83\xc2\xb1': b'\xc3\xb1',
        b'\xc3\x83\xc2\x81': b'\xc3\x81',
        b'\xc3\x83\xc2\x8d': b'\xc3\x8d',
        b'\xc3\x83\xc2\x91': b'\xc3\x91',
        b'\xc3\x83\xe2\x80\xb0': b'\xc3\x89',
        b'\xc3\x83\xe2\x80\x9c': b'\xc3\x93',
        b'\xc3\x83\xc5\xa1': b'\xc3\x9a',
        b'\xc3\x82\xc2\xbf': b'\xc2\xbf',
        b'\xc3\x82\xc2\xa1': b'\xc2\xa1',
        b'\xc3\xa2\xe2\x82\xac\xc5\x93': b'\xc2\xab',
        b'\xc3\xa2\xe2\x82\xac\xc5\xbd': b'\xc2\xbb',
        b'\xc3\xa2\xe2\x82\xac\xc2\xa2': b'\xe2\x80\xa2',
        b'\xc3\xa2\xe2\x82\xac\xe2\x80\x9c': b'\xe2\x80\x93',
        b'\xc3\xa2\xe2\x82\xac\xc2\xa6': b'\xe2\x80\xa6',
    }
    srt = sorted(reps.items(), key=lambda x: len(x[0]), reverse=True)
    for old, new in srt:
        c = data.count(old)
        if c > 0:
            data = data.replace(old, new)
            changes += c
    return data, changes